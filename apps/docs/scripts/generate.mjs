// Builds the docs registry from content/<slug>/{meta.ts,*.tsx} and extracts props tables from the library source.
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import docgen from "react-docgen-typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contentDir = join(root, "content");
const outDir = join(root, "generated");
const libSrc = join(root, "../../packages/datui/src");
await mkdir(outDir, { recursive: true });

const slugs = (await readdir(contentDir, { withFileTypes: true }))
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();

const imports = [];
const entries = [];
const sources = {};
for (const [i, slug] of slugs.entries()) {
  const files = (await readdir(join(contentDir, slug))).filter((f) => f.endsWith(".tsx")).sort();
  imports.push(`import { meta as meta${i} } from "../content/${slug}/meta";`);
  const examples = [];
  for (const [j, file] of files.entries()) {
    const name = file.replace(/\.tsx$/, "");
    imports.push(`import Ex${i}_${j} from "../content/${slug}/${name}";`);
    examples.push(`${JSON.stringify(name)}: Ex${i}_${j}`);
    const code = await readFile(join(contentDir, slug, file), "utf8");
    sources[`${slug}/${name}`] = code.replace(/^"use client";\n\n?/, "").trimEnd();
  }
  entries.push(`  ${JSON.stringify(slug)}: { meta: meta${i}, examples: { ${examples.join(", ")} } },`);
}

await writeFile(
  join(outDir, "registry.ts"),
  `// Generated by scripts/generate.mjs. Do not edit.\nimport type { ComponentType } from "react";\nimport type { DocMeta } from "../lib/types";\n${imports.join("\n")}\n\nexport const registry: Record<string, { meta: DocMeta; examples: Record<string, ComponentType> }> = {\n${entries.join("\n")}\n};\n`,
);
await writeFile(join(outDir, "sources.json"), `${JSON.stringify(sources, null, 2)}\n`);

// Props tables
async function walk(dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(p)));
    else if (e.name.endsWith(".tsx") && !e.name.endsWith(".test.tsx")) out.push(p);
  }
  return out;
}
const parser = docgen.withCustomConfig(join(libSrc, "../tsconfig.json"), {
  savePropValueAsString: true,
  shouldExtractLiteralValuesFromEnum: true,
  shouldRemoveUndefinedFromOptional: true,
  propFilter: (prop) => {
    const file = prop.declarations?.[0]?.fileName ?? prop.parent?.fileName ?? "";
    // Keep datui's own props; drop the hundreds inherited from React's DOM attribute types.
    return !file.includes("node_modules") || prop.name === "className";
  },
});
const props = {};
for (const doc of parser.parse([...(await walk(join(libSrc, "components"))), join(libSrc, "lib/portal.tsx")])) {
  props[doc.displayName] = {
    description: doc.description,
    file: relative(libSrc, doc.filePath),
    props: Object.values(doc.props)
      .map((p) => ({
        name: p.name,
        type: p.type.raw ?? p.type.name,
        required: p.required,
        default: p.defaultValue?.value ?? jsdocDefault(p.description),
        description: p.description.replace(/@default\s+\S+/, "").trim(),
      }))
      .sort((a, b) => Number(b.required) - Number(a.required) || a.name.localeCompare(b.name)),
  };
}
function jsdocDefault(text) {
  return text.match(/@default\s+(.+?)(?:$|\n)/)?.[1];
}
await writeFile(join(outDir, "props.json"), `${JSON.stringify(props, null, 2)}\n`);
console.log(
  `docs: ${slugs.length} pages, ${Object.keys(sources).length} examples, ${Object.keys(props).length} prop tables`,
);
